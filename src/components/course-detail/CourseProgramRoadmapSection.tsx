function getActiveStageIndex(elements: HTMLElement[]) {
  const activationLine = window.innerHeight * 0.55;

  for (let index = elements.length - 1; index >= 0; index -= 1) {
    if (elements[index].getBoundingClientRect().top <= activationLine) {
      return index;
    }
  }

  return 0;
}

